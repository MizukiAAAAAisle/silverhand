import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { validateReactionEmoji } from '../src/api/reactions.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const RUST_RANGES = resolve(
  HERE,
  '../../../rust/crates/backend-core/src/messaging/collaboration/reaction/emoji_ranges.rs',
);

type Range = readonly [number, number];

function rangesWhere(predicate: (scalar: string) => boolean): Range[] {
  const ranges: Array<[number, number]> = [];
  let start: number | null = null;
  let end = 0;
  for (let point = 0; point <= 0x10ffff; point += 1) {
    if (point >= 0xd800 && point <= 0xdfff) continue;
    const accepted = predicate(String.fromCodePoint(point));
    if (accepted) {
      if (start === null) start = point;
      end = point;
    } else if (start !== null) {
      ranges.push([start, end]);
      start = null;
    }
  }
  if (start !== null) ranges.push([start, end]);
  return ranges;
}

function renderRanges(name: string, ranges: readonly Range[]): string {
  return `pub(super) const ${name}: &[(u32, u32)] = &[\n${ranges
    .map(([start, end]) => `    (0x${start.toString(16).toUpperCase()}, 0x${end.toString(16).toUpperCase()}),`)
    .join('\n')}\n];\n`;
}

function render(): string {
  const emoji = rangesWhere(value => validateReactionEmoji(value).ok);
  const whitespace = rangesWhere(value => /\s/u.test(value));
  return [
    '// @generated by packages/shared/tests/reaction-rust-emoji-parity.test.ts.',
    '// The production TypeScript validator signs these scalar projections.',
    renderRanges('REACTION_EMOJI_SCALAR_RANGES', emoji).trimEnd(),
    renderRanges('ECMASCRIPT_WHITESPACE_RANGES', whitespace).trimEnd(),
    '',
  ].join('\n');
}

describe('Rust reaction emoji grammar projection', () => {
  it('is byte-identical to the current production TypeScript authority', () => {
    const signed = render();
    if (process.env.UPDATE_REACTION_RUST_EMOJI === '1') {
      writeFileSync(RUST_RANGES, signed);
    }
    expect(readFileSync(RUST_RANGES, 'utf8')).toBe(signed);
  });
});
