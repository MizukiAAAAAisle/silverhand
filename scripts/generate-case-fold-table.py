#!/usr/bin/env python3
"""Generate the pinned Unicode full case-folding table shipped in
`packages/shared/src/unicode-case-fold.ts`, plus the exhaustive fixture
`packages/shared/tests/fixtures/unicode-case-fold.json` its test asserts against.

#task:2016 — `conversations.title_key` is `NFC(fold(NFC(trim(title))))`, and it is
stored, indexed, and compared ACROSS PROCESSES (backend, renderer, CLI, packaged
daemon). So the fold must be a pure function of DATA WE SHIP, not of whichever
Unicode version the host JS engine happens to carry: `String.prototype.toLowerCase`
is not full case folding at all (`ss` for `ß` is a fold, never a lowercase), and
anything derived from it would silently change meaning on a Node/Electron upgrade
while the already-stored keys stayed put.

SOURCE OF TRUTH = CPython's own `str.casefold()`, which implements Unicode full
case folding (CaseFolding.txt status C + F) from the `unicodedata` tables. Which
revision those tables carry is NOT this script's decision: it is asserted against
`scripts/unicode_pin.py` before a byte is written, so running the generator under
whatever CPython happens to be on PATH cannot quietly rewrite both the table and
its own fixture to an older Unicode. Bumping the version is an edit to that pin —
and a key-affecting one, so it runs with the `title_key` integrity scan.

Usage (from the repo root):

    python3 scripts/generate-case-fold-table.py

Nothing in the build or the test suite calls this: it is a data generator, and its
output is committed. The fixture exists so the compressed table in TypeScript is
proved lossless against every one of the 1500+ mappings rather than reviewed by
eye, and the shared test additionally cross-checks the single-code-point half
against the JS engine's OWN simple-fold oracle (regex `iu` canonicalization) —
an independent implementation, so a transcription error in this generator's output
cannot pass unnoticed.
"""

from __future__ import annotations

import json
import sys
import unicodedata
from pathlib import Path

from unicode_pin import require_expected_unicode_version

MAX_CODE_POINT = 0x110000
REPO_ROOT = Path(__file__).resolve().parent.parent
TABLE_PATH = REPO_ROOT / 'packages/shared/src/unicode-case-fold.ts'
FIXTURE_PATH = REPO_ROOT / 'packages/shared/tests/fixtures/unicode-case-fold.json'


def code_point_name(cp: int) -> str:
    try:
        return unicodedata.name(chr(cp))
    except ValueError:
        return f'U+{cp:04X}'


def escape(text: str) -> str:
    """A JS string literal holding only ASCII escapes.

    Source files never carry raw invisible characters: several fold expansions are
    a base letter plus a COMBINING mark, and one is U+0069 U+0307, which a reviewer
    cannot tell apart from a bare `i` in a proportional font.
    """
    return "'" + ''.join(f'\\u{ord(c):04X}' for c in text) + "'"


def main() -> int:
    unicode_version = require_expected_unicode_version()
    singles: list[tuple[int, int]] = []
    expansions: list[tuple[int, str]] = []
    for cp in range(MAX_CODE_POINT):
        ch = chr(cp)
        folded = ch.casefold()
        if folded == ch:
            continue
        if len(folded) == 1:
            singles.append((cp, ord(folded)))
        else:
            expansions.append((cp, folded))

    # Run-length encoding with a STRIDE, because the two shapes the data actually
    # has are "a contiguous cased alphabet" (A..Z, Greek, Cyrillic, Cherokee: stride
    # 1) and "alternating upper/lower pairs" (Latin Extended-A's Ā/ā, Ă/ă …: stride
    # 2). Greedy per run, longest of the two strides.
    runs: list[tuple[int, int, int, int]] = []
    index = 0
    while index < len(singles):
        start, target = singles[index]
        delta = target - start
        best_length, best_stride = 1, 1
        for stride in (1, 2):
            length = 1
            probe = index + 1
            while (
                probe < len(singles)
                and singles[probe][0] == start + stride * length
                and singles[probe][1] - singles[probe][0] == delta
            ):
                length += 1
                probe += 1
            if length > best_length:
                best_length, best_stride = length, stride
        runs.append((start, start + best_stride * (best_length - 1), best_stride, delta))
        index += best_length

    lines: list[str] = []
    lines.append(f'''// GENERATED by scripts/generate-case-fold-table.py — DO NOT EDIT BY HAND.
//
// Unicode FULL CASE FOLDING (CaseFolding.txt status C + F), pinned as data
// (#task:2016). `packages/shared/tests/unicode-case-fold.test.ts` asserts this
// table reproduces every mapping in `tests/fixtures/unicode-case-fold.json` and
// cross-checks the 1:1 half against the JS engine's own simple-fold oracle.

/**
 * The Unicode revision this table was generated from.
 *
 * `title_key` is derived from it, so a change here CHANGES STORED KEYS: an
 * existing row's title may fold differently than it did when its key was written.
 * Bumping this constant is therefore a migration event, not a dependency update —
 * regenerate, review the diff, and run the `title_key` integrity scan.
 *
 * It is asserted, not observed: the generator refuses to run unless the
 * interpreter's `unicodedata` carries `scripts/unicode_pin.py`'s pinned revision.
 */
export const UNICODE_CASE_FOLD_VERSION = '{unicode_version}';

/**
 * 1:1 mappings, as `[start, end, stride, delta]`: every code point
 * `start, start + stride, … end` folds to itself plus `delta`.
 *
 * Sorted by `start` and non-overlapping, which is what lets {{@link foldCodePoint}}
 * binary-search it. The stride is not a compression trick for its own sake — the
 * data has exactly two shapes, contiguous cased alphabets (stride 1) and
 * alternating upper/lower pairs (stride 2) — and keeping the runs makes the table
 * reviewable per script instead of {len(singles)} anonymous pairs.
 */
const FOLD_RUNS: readonly (readonly [number, number, number, number])[] = [''')
    for start, end, stride, delta in runs:
        if start == end:
            comment = f'{code_point_name(start)} -> U+{start + delta:04X}'
        else:
            comment = (
                f'{code_point_name(start)}..{code_point_name(end)}'
                f' -> U+{start + delta:04X}..U+{end + delta:04X}'
            )
        lines.append(
            f'  [0x{start:04X}, 0x{end:04X}, {stride}, {delta}], // {comment}'
        )
    lines.append('];')
    lines.append('')
    lines.append(f'''/**
 * Mappings whose fold is LONGER than one code point ({len(expansions)} of them), the half no
 * lowercase mapping can express: `ß` folds to `ss`, the Latin and Armenian
 * ligatures decompose, and the Greek iota-subscript forms expand.
 *
 * Values are written as `\\uXXXX` escapes on purpose — several are a base letter
 * plus a combining mark, which is unreviewable as a raw literal.
 */
const FOLD_EXPANSIONS: readonly (readonly [number, string])[] = [''')
    for cp, folded in expansions:
        target_names = ' + '.join(code_point_name(ord(c)) for c in folded)
        lines.append(
            f'  [0x{cp:04X}, {escape(folded)}], // {code_point_name(cp)} -> {target_names}'
        )
    lines.append('];')
    lines.append('')
    lines.append('''const EXPANSION_BY_CODE_POINT = new Map(FOLD_EXPANSIONS);

/**
 * The full case fold of ONE code point, or `null` when it folds to itself.
 *
 * Total over every integer in the Unicode range — unassigned, private-use and
 * surrogate code points all fold to themselves, which is why this returns `null`
 * rather than throwing: folding is a normalization, not a validation, and the
 * domain rule for a title lives in its own validator.
 */
export function foldCodePoint(codePoint: number): string | null {
  const expansion = EXPANSION_BY_CODE_POINT.get(codePoint);
  if (expansion !== undefined) return expansion;
  let low = 0;
  let high = FOLD_RUNS.length - 1;
  while (low <= high) {
    const mid = (low + high) >> 1;
    const [start, end, stride, delta] = FOLD_RUNS[mid]!;
    if (codePoint < start) {
      high = mid - 1;
      continue;
    }
    if (codePoint > end) {
      low = mid + 1;
      continue;
    }
    return (codePoint - start) % stride === 0
      ? String.fromCodePoint(codePoint + delta)
      : null;
  }
  return null;
}

/**
 * Unicode FULL case folding of a string — the caseless-comparison normal form.
 *
 * Full, not simple: the point of a fold is that two spellings a reader would call
 * "the same name in different case" produce the same key, and simple folding
 * leaves `ß` and `ẞ` on opposite sides of that line. Idempotent (`fold(fold(x))
 * === fold(x)`), and a pure function of {@link UNICODE_CASE_FOLD_VERSION}'s data:
 * no `toLowerCase`, so the answer does not depend on the host engine's Unicode
 * revision.
 *
 * NOT a locale operation. Turkic dotless-i is deliberately absent (CaseFolding's
 * `T` mappings are excluded): a per-locale key would make the same title collide
 * in one workspace and not in another.
 */
export function foldCase(input: string): string {
  let out = '';
  for (const character of input) {
    const folded = foldCodePoint(character.codePointAt(0)!);
    out += folded ?? character;
  }
  return out;
}''')

    TABLE_PATH.write_text('\n'.join(lines) + '\n', encoding='utf-8')

    fixture = {
        'unicodeVersion': unicode_version,
        'generator': 'scripts/generate-case-fold-table.py',
        # Hex, never raw characters: this fixture is the ORACLE, so it has to be
        # readable and diffable without a Unicode-aware editor.
        'mappings': {
            f'{cp:04X}': ' '.join(f'{ord(c):04X}' for c in folded)
            for cp, folded in sorted(
                [(cp, chr(target)) for cp, target in singles] + expansions
            )
        },
    }
    FIXTURE_PATH.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE_PATH.write_text(json.dumps(fixture, indent=2) + '\n', encoding='utf-8')

    print(
        f'unicode {unicode_version}: '
        f'{len(runs)} runs + {len(expansions)} expansions '
        f'= {len(singles) + len(expansions)} mappings'
    )
    return 0


if __name__ == '__main__':
    sys.exit(main())
