#!/usr/bin/env python3
"""Derive the Android launcher icon from the shared Brandmark vector.

Source of truth: packages/app-ui/src/components/brand/brandmark.tsx (inline SVG).
The two path `d` strings are copied verbatim; the SVG transform is reproduced as
nested VectorDrawable groups so the geometry is never re-traced or re-fitted.

Outputs (all under apps/android/app/src/main/res):
  drawable/ic_launcher_foreground.xml   adaptive foreground, 108dp canvas
  drawable/ic_launcher_monochrome.xml   Android 13+ themed-icon layer
  values/colors.xml                     ic_launcher_background = #FEFEFE
  mipmap-anydpi-v26/ic_launcher.xml     adaptive icon (background/foreground/monochrome)
  mipmap-<density>/ic_launcher.png      48/72/96/144/192 legacy fallback

Rendering uses headless Chrome (no image library required): the legacy PNGs are
rasterised by the browser at their exact target size, then cropped out of a
1024x1024 screenshot.

  python3 generate_launcher_icons.py --write   # write the resources
  python3 generate_launcher_icons.py --check   # verify committed resources
"""
from __future__ import annotations

import argparse
import pathlib
import re
import shutil
import struct
import subprocess
import sys
import tempfile
import zlib

REPO = pathlib.Path(__file__).resolve().parents[3]
RES = REPO / 'apps/android/app/src/main/res'
SOURCE = REPO / 'packages/app-ui/src/components/brand/brandmark.tsx'
CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'

VIEWPORT = 1254.0          # SVG viewBox side, kept as the VectorDrawable viewport
CANVAS_DP = 108.0          # adaptive icon canvas
GLYPH_HEIGHT_DP = 64.0     # see docs/design notes in the task record
BACKGROUND = '#FEFEFE'
DENSITIES = {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}
SCREENSHOT = 1024


def fail(message: str) -> 'None':
    raise SystemExit('generate_launcher_icons: ' + message)


def chrome(*args: str) -> str:
    if not pathlib.Path(CHROME).is_file():
        fail(f'headless Chrome not found at {CHROME!r}')
    return subprocess.check_output([CHROME, '--headless', '--disable-gpu', '--no-sandbox',
                                    '--hide-scrollbars', '--force-device-scale-factor=1',
                                    f'--user-data-dir={chrome.profile}', *args],
                                   stderr=subprocess.DEVNULL).decode()


chrome.profile = tempfile.mkdtemp(prefix='launcher-icons-chrome-')


def read_source():
    text = SOURCE.read_text()
    paths = re.findall(r'd="([^"]+)"', text)
    transform = re.search(r'<g transform="([^"]+)"', text).group(1)
    if len(paths) != 2:
        fail(f'expected 2 paths in {SOURCE}, found {len(paths)}')
    if transform != 'translate(0,1254) scale(0.1,-0.1)':
        fail(f'unexpected Brandmark transform: {transform!r}')
    return paths, transform


def glyph_box(paths, transform):
    """Geometric bbox of the glyph in viewBox space, via SVG getBBox (not pixels)."""
    html = ('<html><body><svg viewBox="0 0 1254 1254">'
            f'<g transform="{transform}">'
            + ''.join(f'<path d="{d}"/>' for d in paths)
            + '</g></svg><script>window.onload=()=>{const r=[...document.querySelectorAll("path")]'
              '.map(p=>{const b=p.getBBox();return [b.x,b.y,b.width,b.height]});'
              'document.body.innerHTML="<pre>BBOX:"+JSON.stringify(r)+"</pre>"}</script></body></html>')
    page = pathlib.Path(chrome.profile) / 'bbox.html'
    page.write_text(html)
    dom = chrome('--virtual-time-budget=2000', '--dump-dom', f'file://{page}')
    match = re.search(r'BBOX:(\[\[.*?\]\])', dom)
    if not match:
        fail('could not read SVG getBBox output')
    raw = __import__('json').loads(match.group(1))
    boxes = [(x / 10, 1254 - (y + h) / 10, w / 10, h / 10) for x, y, w, h in raw]
    x0 = min(b[0] for b in boxes)
    y0 = min(b[1] for b in boxes)
    x1 = max(b[0] + b[2] for b in boxes)
    y1 = max(b[1] + b[3] for b in boxes)
    return x0, y0, x1, y1


def vector_xml(paths: str, box, height_dp: float) -> str:
    x0, y0, x1, y1 = box
    glyph_h = y1 - y0
    scale = height_dp * VIEWPORT / (glyph_h * CANVAS_DP)
    translate_x = VIEWPORT / 2 - scale * (x0 + x1) / 2
    translate_y = VIEWPORT / 2 - scale * (y0 + y1) / 2
    body = ''.join('\n        <path android:fillColor="#000000" android:fillType="nonZero"'
                   f' android:pathData="{d}"/>' for d in paths)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/android/scripts/generate_launcher_icons.py; do not edit by hand.
     Path data is copied verbatim from packages/app-ui/src/components/brand/brandmark.tsx. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="1254"
    android:viewportHeight="1254">
    <!-- Outer group: place the glyph on the {CANVAS_DP:.0f}dp canvas at {height_dp:g}dp tall, centred.
         Inner group: the Brandmark's own translate(0,1254) scale(0.1,-0.1), kept as-is so the
         vertical flip and the traced winding (nonZero) survive the port. -->
    <group
        android:translateX="{translate_x:.4f}"
        android:translateY="{translate_y:.4f}"
        android:scaleX="{scale:.6f}"
        android:scaleY="{scale:.6f}">
        <group
            android:translateY="1254"
            android:scaleX="0.1"
            android:scaleY="-0.1">{body}
        </group>
    </group>
</vector>
'''


def colors_xml() -> str:
    return f'''<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">{BACKGROUND}</color>
</resources>
'''


def adaptive_xml() -> str:
    return '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
'''


def legacy_svg(paths, transform) -> str:
    """Legacy artwork keeps the Brandmark's own framing: no re-centring, no extra scale."""
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1254 1254" '
            f'width="{SCREENSHOT}" height="{SCREENSHOT}">'
            f'<rect width="1254" height="1254" fill="{BACKGROUND}"/>'
            f'<g transform="{transform}" fill="#000000" stroke="none">'
            + ''.join(f'<path d="{d}"/>' for d in paths) + '</g></svg>')


def render_legacy(svg: str, size: int, workdir: pathlib.Path) -> bytes:
    svg_path = workdir / 'legacy.svg'
    svg_path.write_text(svg)
    html = ('<html><head><style>html,body{margin:0;padding:0;overflow:hidden}'
            'img{display:block}</style></head>'
            f'<body><img src="legacy.svg" width="{size}" height="{size}"></body></html>')
    html_path = workdir / 'legacy.html'
    html_path.write_text(html)
    shot = workdir / 'shot.png'
    chrome(f'--window-size={SCREENSHOT},{SCREENSHOT}', f'--screenshot={shot}', f'file://{html_path}')
    return crop_png(shot.read_bytes(), size)


def png_size(data: bytes):
    if data[:8] != b'\x89PNG\r\n\x1a\n':
        fail('not a PNG')
    width, height, depth, color, _, _, interlace = struct.unpack('>IIBBBBB', data[16:29])
    return width, height, depth, color, interlace


def png_pixels(data: bytes):
    """Decode an 8-bit non-interlaced RGB/RGBA PNG into (width, height, rows)."""
    width, height, depth, color_type, interlace = png_size(data)
    if depth != 8 or color_type not in (2, 6) or interlace != 0:
        fail(f'unsupported PNG: depth={depth} color={color_type} interlace={interlace}')
    channels = 3 if color_type == 2 else 4
    pos, idat = 8, b''
    while pos < len(data):
        length, kind = struct.unpack('>I4s', data[pos:pos + 8])
        chunk = data[pos + 8:pos + 8 + length]
        if kind == b'IDAT':
            idat += chunk
        pos += 12 + length
    raw = zlib.decompress(idat)
    stride = width * channels
    rows, previous = [], bytearray(stride)
    for y in range(height):
        filt = raw[y * (stride + 1)]
        line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            left = line[i - channels] if i >= channels else 0
            up = previous[i]
            diagonal = previous[i - channels] if i >= channels else 0
            if filt == 1:
                line[i] = (line[i] + left) & 0xFF
            elif filt == 2:
                line[i] = (line[i] + up) & 0xFF
            elif filt == 3:
                line[i] = (line[i] + (left + up) // 2) & 0xFF
            elif filt == 4:
                p = left + up - diagonal
                pa, pb, pc = abs(p - left), abs(p - up), abs(p - diagonal)
                line[i] = (line[i] + (left if pa <= pb and pa <= pc else up if pb <= pc else diagonal)) & 0xFF
            elif filt != 0:
                fail(f'bad PNG filter {filt}')
        rows.append(bytes(line))
        previous = line
    return width, height, rows, channels


def crop_png(data: bytes, size: int) -> bytes:
    """Crop the top-left size x size square out of a Chrome screenshot, re-encoding with stdlib zlib."""
    width, height, rows, channels = png_pixels(data)
    if size > width or size > height:
        fail(f'screenshot {width}x{height} smaller than requested {size}')
    out = bytearray()
    for y in range(size):
        out.append(0)
        out += rows[y][:size * channels]
    color_type = 2 if channels == 3 else 6

    def chunk(kind: bytes, payload: bytes) -> bytes:
        return (struct.pack('>I', len(payload)) + kind + payload
                + struct.pack('>I', zlib.crc32(kind + payload) & 0xFFFFFFFF))

    header = struct.pack('>IIBBBBB', size, size, 8, color_type, 0, 0, 0)
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', header)
            + chunk(b'IDAT', zlib.compress(bytes(out), 9)) + chunk(b'IEND', b''))


def dark_box(data: bytes):
    width, height, rows, channels = png_pixels(data)
    xs, ys = [], []
    for y, row in enumerate(rows):
        for x in range(width):
            r, g, b = row[x * channels], row[x * channels + 1], row[x * channels + 2]
            if (r + g + b) / 3 < 128:
                xs.append(x)
                ys.append(y)
    if not xs:
        fail('generated legacy icon has no dark pixels')
    return min(xs), min(ys), max(xs) + 1, max(ys) + 1


def expected_files(paths, transform, box, workdir, height_dp):
    files = {
        'drawable/ic_launcher_foreground.xml': vector_xml(paths, box, height_dp).encode(),
        'drawable/ic_launcher_monochrome.xml': vector_xml(paths, box, height_dp).encode(),
        'values/colors.xml': colors_xml().encode(),
        'mipmap-anydpi-v26/ic_launcher.xml': adaptive_xml().encode(),
    }
    legacy = legacy_svg(paths, transform)
    for name, size in DENSITIES.items():
        files[f'mipmap-{name}/ic_launcher.png'] = render_legacy(legacy, size, workdir)
    return files


def check(files, res: pathlib.Path):
    problems = []
    for name, data in sorted(files.items()):
        target = res / name
        if not target.is_file():
            problems.append(f'missing {name}')
            continue
        if name.endswith('.png'):
            want = DENSITIES[name.split('/')[0].removeprefix('mipmap-')]
            actual = png_size(target.read_bytes())
            if actual[:2] != (want, want):
                problems.append(f'{name}: {actual[0]}x{actual[1]} != {want}x{want}')
            continue
        if target.read_bytes() != data:
            problems.append(f'{name}: content differs')
    for line in problems:
        print('FAIL ' + line)
    if problems:
        raise SystemExit(1)
    print(f'OK {len(files)} generated files match committed resources')


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--write', action='store_true', help='write resources into the repo')
    parser.add_argument('--check', action='store_true', help='verify committed resources')
    parser.add_argument('--res', type=pathlib.Path, default=RES, help='target resource directory')
    parser.add_argument('--glyph-height-dp', type=float, default=GLYPH_HEIGHT_DP)
    args = parser.parse_args()
    if not args.write and not args.check:
        parser.error('choose --write or --check')
    paths, transform = read_source()
    box = glyph_box(paths, transform)
    print('glyph bbox (viewBox): x=[%.3f, %.3f] y=[%.3f, %.3f]' % (box[0], box[2], box[1], box[3]))
    workdir = pathlib.Path(chrome.profile)
    files = expected_files(paths, transform, box, workdir, args.glyph_height_dp)
    if args.check:
        check(files, args.res)
        return 0
    for name, data in files.items():
        target = args.res / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        print('wrote', target.relative_to(REPO))
    return 0


if __name__ == '__main__':
    status = main()
    shutil.rmtree(chrome.profile, ignore_errors=True)
    sys.exit(status)
